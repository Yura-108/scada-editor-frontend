/**
 * Короткая подпись тега для интерфейса.
 *
 * `tag_id` — это путь узла в дереве каналов, точками: `проект.сцена.устройство.тег`.
 * Целиком он в подпись не помещается, а первые два сегмента в редакторе и так известны —
 * проект выбран в шапке, схема открыта на холсте. Поэтому в подписи их не показываем.
 *
 * Только представление: в модели и в запросах `tag_id` остаётся полным путём — по нему
 * рантайм и находит канал.
 */

/** Сколько ведущих сегментов пути скрывается: проект и схема. */
const HIDDEN_PREFIX_SEGMENTS = 2;

export function shortTagPath(path: string | null | undefined): string {
  if (!path) return "";

  const parts = path.split(".");
  // Отрезать нечего: пустая подпись хуже длинной, показываем как есть.
  if (parts.length <= HIDDEN_PREFIX_SEGMENTS) return path;

  return parts.slice(HIDDEN_PREFIX_SEGMENTS).join(".");
}
