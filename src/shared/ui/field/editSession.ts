/**
 * Начало, конец и отмена одной правки поля. Поле сообщает о них тому, кто ведёт историю:
 * редактор склеивает всю правку в один шаг undo (`historyEditing` в модуле редактора).
 * Поле само об истории ничего не знает.
 */
export interface EditSession {
  /** Первое изменение правки — до первого `onCommit`/`onChange`. */
  onEditStart?: () => void;
  /** Правка закончена: потеря фокуса или Enter. */
  onEditEnd?: () => void;
  /** Правка отменена Escape — значение уже возвращено, след в истории не нужен. */
  onEditCancel?: () => void;
}
