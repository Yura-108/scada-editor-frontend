/**
 * Импорт базы каналов из `.cdbx` — контракт
 * `docs/contract/2026-09-22-cdbx-import-contract.md` (сверено с кодом бэкенда, коммит
 * `44c7729`: `CdbxImportReport`, `ImportParamTypes`).
 */

/** Итог импорта. Все три списка могут быть пустыми — это нормальный, а не подозрительный случай. */
export interface CdbxImportReport {
  /** Путь созданного проекта: «Барановичи-1.BN1_MCA2». */
  root: string;
  nodes: number;
  channels: number;
  /** Каналы, чей путь занял другой канал: одна переменная ПЛК была в двух группах. */
  merged: string[];
  /** Поля вне таблицы типов — тип данных угадан, стоит проверить руками. */
  guessedType: string[];
  /** Имена без поля — в базу не попали вовсе. */
  skipped: string[];
}

/**
 * Имена параметров, которые заводит импорт. Ищем именно ПО ИМЕНИ, а не по id: бэкенд сам
 * так делает (`ImportParamTypes.ids()`), потому что на разных стендах id справочника
 * расходятся, и привязка к числу тихо сломалась бы на чужой базе.
 */
export const PARAM_PLC_NAME = "Имя в ПЛК";
export const PARAM_DATA_TYPE = "Тип данных";
/** Метка «проект создан импортом». Без неё бэкенд запрещает удаление проекта целиком. */
export const PARAM_IMPORT_SOURCE = "Источник импорта";
