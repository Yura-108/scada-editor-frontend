/**
 * Порог отрисовки текста по зуму (level of detail).
 *
 * Тем же приёмом, что сетка (`gridPattern.ts`): ниже определённого размера на экране
 * содержимое перестаёт быть содержимым и становится грязью. У сетки клетка мельче ~5 px
 * сливается в заливку, у текста строки мельче ~5 px сливаются в кашу из наложенных
 * прямоугольников — и при этом стоят полной отрисовки глифов.
 *
 * Числа, из-за которых порог понадобился: лист A0 от CONTUR — 21520 x 15240 единиц, то
 * есть зум «весь лист» около 0.055, и на нём каждая подпись устройства (кегль 80 единиц
 * по договорённости от 02.09.2026) занимает 4.4 px. Читаемой строка становится примерно
 * с 8 px, то есть с зума 0.10 — ровно там, где вписывается типовой лист A3.
 *
 * Гасим только глифы: габариты, выделение и попадание в рамку выделения не меняются.
 */
export const TEXT_MIN_SCREEN_PX = 5;

/** Виден ли текст такого кегля при таком зуме — то есть стоит ли его вообще рисовать. */
export const isTextVisibleAtZoom = (fontSize: number, zoom: number): boolean =>
  fontSize * zoom >= TEXT_MIN_SCREEN_PX;
