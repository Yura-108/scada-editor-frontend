/**
 * Границы зума — ОДИН источник на весь редактор.
 *
 * Раньше их было две независимые копии (кнопки зума и колесо), и разъезжались
 * они молча: колесо упиралось в одну границу, «вписать» — в другую.
 *
 * Нижняя граница рассчитана на самый крупный лист, который переносят из Eplan:
 * A0 у CONTUR — 21520 x 15240 единиц, а это 0.056 в рабочем окне 1500x850 и
 * уже 0.039 на ноутбучном 1000x600. Прежние 0.2 не давали увидеть целиком даже
 * A3 (0.10).
 */
export const ZOOM_MIN = 0.03;
export const ZOOM_MAX = 3;

export const clampZoom = (z: number): number =>
  Math.min(Math.max(z, ZOOM_MIN), ZOOM_MAX);
