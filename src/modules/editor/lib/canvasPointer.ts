/**
 * Последняя позиция курсора над холстом — в МИРОВЫХ координатах.
 *
 * Держим модульной переменной, а не в сторе, намеренно: обновляется она на каждый
 * `mousemove`, а любая запись в стор дёргает подписчиков — при частоте движения мыши это
 * означало бы перерисовку сцены десятки раз в секунду ровно ради того, чего никто не
 * рисует. Читатель у значения один и читает его в момент действия (вставка), а не в рендере.
 *
 * Значение живёт до следующего движения мыши: если курсор ушёл на панель и там нажали
 * Ctrl+V, вставка встанет в последнюю точку внутри холста — это ближе к ожидаемому, чем
 * отказ от позиции вовсе.
 */
let lastPointerWorld: {x: number; y: number} | null = null;

export const setCanvasPointerWorld = (point: {x: number; y: number}): void => {
  lastPointerWorld = point;
};

export const getCanvasPointerWorld = (): {x: number; y: number} | null => lastPointerWorld;

/** Сброс при смене документа: координата от чужой схемы смысла не имеет. */
export const clearCanvasPointerWorld = (): void => {
  lastPointerWorld = null;
};
